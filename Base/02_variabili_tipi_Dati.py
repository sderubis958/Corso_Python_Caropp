"""
    Tipi dati in python
    int = intero
    str = string
    float = decimale, float (numeri con virgola)
    bool = booleano
"""

nome = 'Giuseppino'

# stampa il tipo di dato della variabile nome
print(type(nome))
print(nome)

# >class 'int' >
eta = 65

# stampa il tipo di dato della variabile eta
print(type(eta))
print(eta)

# >class 'float' >
stipendio = 1.800
print(type(stipendio))
print(stipendio)    

# >class 'bool' >cls

lavoratore = True
print(type(lavoratore)) 
print(lavoratore)

