"""gli operatori sono:
    + ; - ; * ; / ; // ; % ; **
"""

num1 = 12
num2 = 30

somma = num1 + num2
print('la somma di ', num1, ' e ', num2, ' è: ', somma)
print(somma)

resto_mul = num1 * num2
print('il prodotto di ', num1, ' e ', num2, ' è: ', resto_mul)

risultato_sott = num1 - num2
print('la differenza di ', num1, ' e ', num2, ' è: ', risultato_sott)   

resto_div = num1 / num2
print('la divisione di ', num1, ' e ', num2, ' è: ', resto_div)             

resto_modu = num1 % num2
print('il resto della divisione di ', num1, ' e ', num2, '  è: ', resto_modu)

resto_nin = num1 // num2
print('il quoziente della divisione di ', num1, ' e ', num2, '  è: ', resto_nin)

resto_pot = num1 ** num2
print('il risultato della potenza di ', num1, ' e ', num2, '  è: ', resto_pot)

